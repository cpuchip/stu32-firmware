#!/usr/bin/env python3
"""gen_font: firmware/font5x7.txt (the drawing) to firmware/font5x7.c (unit 018).

    python3 scripts/gen_font.py            # rewrite font5x7.c
    python3 scripts/gen_font.py --check    # exit 1 if font5x7.c is not what the drawing gives

Each glyph is seven rows of five columns; a row becomes one byte, bit 4 the left column.
Standard library only.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
TXT = os.path.join(HERE, "..", "firmware", "font5x7.txt")
OUT = os.path.join(HERE, "..", "firmware", "font5x7.c")


def glyphs():
    out, cur = [], None
    for n, line in enumerate(open(TXT, encoding="utf-8"), 1):
        line = line.rstrip("\n")
        if not line or line.startswith("# "):        # a row is five of # and ., never a blank
            continue
        if line.startswith("U+"):
            cur = (int(line[2:6], 16), [])
            out.append(cur)
            continue
        if cur is None or len(line) != 5 or set(line) - {"#", "."}:
            sys.exit(f"font5x7.txt:{n}: not a glyph row: {line!r}")
        cur[1].append(line)
    cps = [cp for cp, _ in out]
    if cps != sorted(set(cps)):
        sys.exit("font5x7.txt: code points must be unique and ascending")
    for cp, rows in out:
        if len(rows) != 7:
            sys.exit(f"font5x7.txt: U+{cp:04X} has {len(rows)} rows")
    return out


def emit():
    lines = ["/* font5x7: generated by scripts/gen_font.py from font5x7.txt (the drawing: edit that). Our own",
             " * face, unit 018. Sorted by code point, for a binary search. */",
             '#include "font5x7.h"', "", "const font_glyph FONT5X7[] = {"]
    for cp, rows in glyphs():
        bits = ", ".join("0x%02X" % int(r.replace("#", "1").replace(".", "0"), 2) for r in rows)
        lines.append(f"    {{0x{cp:04X}, {{{bits}}}}},")
    lines += ["};", "const int FONT5X7_COUNT = (int)(sizeof FONT5X7 / sizeof FONT5X7[0]);", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    text = emit()
    if "--check" in sys.argv:
        sys.exit(0 if open(OUT, encoding="utf-8").read() == text else 1)
    open(OUT, "w", encoding="utf-8").write(text)
