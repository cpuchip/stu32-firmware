#!/usr/bin/env python3
"""Unit 089: the ops' names as core/calc.h spells them, without AB_, in enum order: tests/opnames.h, for the vectors'
%ROW dump (the op that made a row) and tests/rows_test.c's census. Committed, as keymap.c is.

    python3 scripts/gen_opnames.py            write tests/opnames.h
    python3 scripts/gen_opnames.py --check    exit 1 if tests/opnames.h is not what core/calc.h gives
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def names():
    src = open(os.path.join(ROOT, "core", "calc.h"), encoding="utf-8").read()
    start = src.index("typedef enum {\n    AB_K0")
    body = src[start:src.index("} ab_op;", start)]
    body = re.sub(r"/\*.*?\*/", "", body, flags=re.S).split("{", 1)[1]
    out = re.findall(r"\b(AB_[A-Z0-9_]+)\b", body)
    if any("=" in part for part in body.split(",")):
        sys.exit("gen_opnames: an op is given a value; the names would be out of order")
    return [n[3:] for n in out]


def text():
    ns = names()
    lines = ["/* Generated by scripts/gen_opnames.py from core/calc.h's ab_op (unit 089): don't edit. */",
             "#ifndef AB_OPNAMES_H", "#define AB_OPNAMES_H", "",
             f"#define AB_OPNAMES_N {len(ns)}",
             "static const char *const AB_OPNAMES[AB_OPNAMES_N] = {"]
    row = "   "
    for n in ns:
        item = f' "{n}",'
        if len(row) + len(item) > 118:
            lines.append(row)
            row = "   "
        row += item
    lines.append(row)
    lines += ["};", "", "#endif", ""]
    return "\n".join(lines)


def main():
    path = os.path.join(ROOT, "tests", "opnames.h")
    want = text()
    if "--check" in sys.argv[1:]:
        have = open(path, encoding="utf-8").read() if os.path.exists(path) else ""
        if have != want:
            print("gen_opnames: tests/opnames.h is stale (python3 scripts/gen_opnames.py)", file=sys.stderr)
            sys.exit(1)
        print("gen_opnames: tests/opnames.h is current")
        return
    open(path, "w", encoding="utf-8").write(want)
    print(f"gen_opnames: {len(names())} ops")


main()
