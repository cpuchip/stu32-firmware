#!/usr/bin/env python3
"""gen_bringup: Rev A's bring-up session (unit 061), device/reva/bringup.txt, for talk.py over the USB-C port.

    python3 device/reva/gen_bringup.py            # rewrite bringup.txt
    python3 device/reva/gen_bringup.py --check    # exit 1 if bringup.txt is not what this gives

It follows step 8 of abacus's docs/hw/rev-a-bring-up.md, one section per row (abacus #6106). What the log can judge
is an expect; what it cannot (a flicker, a tone, a current) is a confirm, answered y or n by the person at the board,
with what to look for. The key walk is made from firmware/keymap.c, the table the firmware's KEYS echo prints from
(reva_main.c's echo_key), so a prompt and the echo it waits for cannot drift apart. Standard library only.
"""
import codecs
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
KEYMAP = os.path.join(HERE, "..", "..", "firmware", "keymap.c")
OUT = os.path.join(HERE, "bringup.txt")
COLS = 6
ENTRY = re.compile(r'^\s*\[(\d+)\] = \{\{(KM_\w+), [^,]+, (-?\d+), [^,]+, "((?:[^"\\]|\\.)*)"\}')


def keys():
    """(number, row, column, echo name, a hint for the person) for every key the face table has, as echo_key names it"""
    out = []
    for line in open(KEYMAP, encoding="utf-8"):
        m = ENTRY.match(line)
        if not m:
            continue
        n, kind, arg, legend = int(m.group(1)), m.group(2), int(m.group(3)), m.group(4)
        legend = codecs.escape_decode(legend.encode())[0].decode("utf-8")
        if kind == "KM_SOFT":
            name, hint = f"SOFT{arg + 1}", f"the top row's key {arg + 1}, under the screen"
        elif kind == "KM_SHIFT":
            name = "GOLD" if arg == 1 else "BLUE"
            hint = f"the {name.lower()} shift key"
        elif kind == "KM_NONE" and not legend:
            continue                                        # no switch there
        else:
            name, hint = legend or "-", legend or "-"
        out.append((n, n // COLS, n % COLS, name, hint))
    if len(out) != 43:
        sys.exit(f"gen_bringup: {len(out)} keys in keymap.c, not the layout's 43")
    return out


def by_name(walk, name):
    return next(k for k in walk if k[3] == name)


def echo(k, what="down"):
    n, r, c, name, _ = k
    return f"key: {n} r{r} c{c} {name} {what}"


def session():
    walk = keys()
    sin, cos, e, back = by_name(walk, "SIN"), by_name(walk, "COS"), by_name(walk, "E"), by_name(walk, "←")
    enter = by_name(walk, "ENTER")
    assert (sin[1], cos[1]) == (e[1] - 1, back[1] - 1) and (sin[2], cos[2]) == (e[2], back[2]), "the ghost square moved"
    L = []
    w = L.append
    w("# Rev A's bring-up session (unit 061): step 8 of abacus's docs/hw/rev-a-bring-up.md, for talk.py over the USB-C")
    w("# port. Generated by device/reva/gen_bringup.py from firmware/keymap.c: edit the generator, not this file.")
    w("#")
    w("#   python talk.py PORT bringup.log bringup.txt      (FLASH.md: the port's name on lepton and on Windows)")
    w("#")
    w("# An expect is judged from the log; a confirm is answered y or n here by the person at the board. bringup.log is")
    w("# what goes back to abacus. On USB power it never turns itself off, and OFF is a soft off (068): blank, the port")
    w("# stays, C turns it on. Deep sleep is on the cell alone. Keys by number (keys.h: row * 6 + column), as accept.txt: 1 37,")
    w("# 2 38, 3 39, 0 43, . 44, ENTER 18, + 46, XEQ 24, GOLD 30, 4 31, 9 27, R/S 45, C 42, soft keys 0-5; A 6.")
    w("")
    w("# ---- flash: QIO, the 16 MB header, a save and a setting across a pinhole reset; IO0's strap; the 32 KB icache's heap")
    w("say Rev A bring-up (unit 061). Resetting the board through its USB port.")
    w("# (068: a reset passes on a new boot; X reports the boot's reason and the flash: io= the mode the driver runs,")
    w("# chip= its size, header= the image header's DIO/16MB, so a port that reopens after the boot lines, as on Windows,")
    w("# still checks them)")
    w("reset")
    w("send X")
    w("expect flash: io=QIO chip=16MB header=DIO/16MB")
    w("expect-range soc 0 100")
    w("# RADIX , (GOLD 3, soft key 2), a setting; then 1.5 ENTER, the stack")
    w("send K30")
    w("send K39")
    w("send K1")
    w("send K37")
    w("send K44")
    w("send K32")
    w("send K18")
    w("send X")
    w("expect state: X=1.5 stop")
    w("expect radix=,")
    w("send SAVE")
    w("expect save:")
    w("say Press the pinhole reset (EN) once now. The USB port goes away and comes back.")
    w("wait talk.py: port open again 120")
    w("reset")
    w("send X")
    w("expect state: X=1.5 stop")
    w("expect radix=,")
    w("# RADIX . again, saved")
    w("send K30")
    w("send K39")
    w("send K0")
    w("send X")
    w("expect radix=.")
    w("send SAVE")
    w("expect save:")
    w("# the matrix's row: a key held at power-up makes no event (a 2 typed would replace 1.5 in X)")
    w("say Hold the 2 key down now, and keep holding it until asked to let go.")
    w("sleep 3")
    w("reset")
    w("say Let go of 2 now.")
    w("sleep 3")
    w("send X")
    w("expect state: X=1.5 stop")
    w("")
    w("# ---- the gauge: version (above), percent, voltage; CHG_N and PGOOD_N (its first sample is 30 s after boot). One X")
    w("# for each field: an expect reads a line once.")
    w("say The gauge's first reading comes 30 s after boot: waiting.")
    w("sleep 35")
    w("send X")
    w("expect-range soc 0 100")
    w("send X")
    w("expect-range vbat 3000000 4300000")
    w("send X")
    w("expect-range pgood_n 0 0")
    w("send X")
    w("expect-range chg_n 0 1")
    w("confirm chg_n above is 0 while a fitted cell charges, 1 with no cell or a full one: does it match this board?")
    w("confirm With a USB meter: the board draws at most about 0.5 A while charging (EN1 and EN2: USB500)? (n if not measured)")
    w("")
    w("# ---- the LS027 and EXTCOMIN: the image, the ULP's inversion awake")
    w("send X")
    w("sleep 5")
    w("send X")
    w("expect-grows ulp-edges")
    w("confirm Is the screen showing 1.5 in the X line, sharp, with no flicker and no faint ghost of an older image?")
    w("")
    w("# ---- the matrix: each key once, echoed with its number, row, column and legend")
    w("send KEYS")
    w("expect keys: echo on")
    w("say Press each key when asked, once. Each has 60 s.")
    for k in walk:
        w(f"say Press {k[4]} (row {k[1]}, column {k[2]})")
        w(f"expect {echo(k)} 60")
    w("send K42")
    w("send K42")
    w("# debounce: one press, one down")
    w(f"say Press ENTER once, firmly.")
    w(f"expect {echo(enter)} 30")
    w(f"expect-none {echo(enter)} 3")
    w("# two and three keys at once; a ghost would be the square's fourth corner")
    w(f"say Hold SIN and COS together for a second, then release both.")
    w(f"expect {echo(sin)} 30")
    w(f"expect {echo(cos)} 10")
    w(f"expect {echo(cos, 'up')} 10")
    w(f"say Now hold SIN, COS and E together for a second, then release all three.")
    w(f"expect {echo(sin)} 30")
    w(f"expect-none key: {back[0]} r{back[1]} c{back[2]} 8")
    w(f"confirm Did the echo above list exactly SIN, COS and E going down and up (nothing else, no ←)?")
    w("send K42")
    w("# C and R/S stop a running program (accept.txt's program: LBL A, 1, +, GTO A)")
    for key in (30, 27, 0, 30, 24, 6, 37, 46, 30, 31, 6, 30, 27, 0):
        w(f"send K{key}")
    w("send X")
    w("expect prgm=0")
    w("send K43")
    w("send K24")
    w("send K6")
    w("expect run: started")
    w("say A program is running. Press R/S on the keyboard to stop it.")
    w("expect run: stopped 60")
    w("send K24")
    w("send K6")
    w("expect run: started")
    w("say Running again. Press C on the keyboard to stop it.")
    w("expect run: stopped 60")
    w("send KEYS")
    w("expect keys: echo off")
    w("")
    w("# ---- the piezo: VOL's five levels (IO46's strap: the normal boot above)")
    for v in range(5):
        w(f"send VOL{v}")
        w("send BEEP")
        w("sleep 1")
    w("confirm Five beeps: the first silent, then each louder than the last?")
    w("send VOL4")
    w("")
    w("# ---- OFF on USB is a soft off (068): the screen blank, the port stays, keys dropped, C alone turns it on")
    w("say Press GOLD then C (OFF), holding C for a second. On USB the screen goes blank and the port stays.")
    w("expect save: 60")
    w("sleep 3")
    w("send X")
    w("expect off=1")
    w("confirm Is the screen blank?")
    w("say Press 5 (nothing should happen), then press C to turn it on.")
    w("sleep 10")
    w("send X")
    w("expect off=0")
    w("confirm Is the screen back as it was, and did C chirp?")
    w("")
    w("# ---- deep sleep on the cell (USB out): C on IO0, OFF waiting for C's release, the image held, the RTC and the ULP")
    w("send TIME 10:00")
    w("expect time: set 10:00:00")
    w("say With the cell fitted, unplug USB. Press GOLD then C (OFF), and hold C for 2 s. The screen should keep its image.")
    w("say After 20 s, check the screen, then press C to wake it, and plug USB back in.")
    w("wait talk.py: port open again 300")
    w("confirm After 20 s off, was the screen still showing its image, unchanged, and did it stay off until C?")
    w("sleep 3")
    w("send X")
    w("expect-grows ulp-edges")
    w("send X")
    w("expect clock=10:0")
    w("send X")
    w("expect wake=EXT1 pins=0x1")
    w("")
    w("# ---- auto-off on the cell (abacus #7591): idle past the off time, it stays off until C. 949a8fd's auto-off on USB")
    w("# woke at once (the light sleep's GPIO wakes armed into deep sleep, 068 (5)): one boot per C, woken by C (EXT1)")
    w("send X")
    w("expect off=10")
    w("remember boots")
    w("say With the cell fitted, unplug USB and leave the calculator untouched for 12 minutes (it turns off at 10).")
    w("say Then look at it (it should have stayed off, no chirp), press C to wake it, and plug USB back in.")
    w("wait talk.py: port open again 1200")
    w("confirm Did it turn itself off at about 10 minutes and stay off (no chirp, no restart) until C?")
    w("sleep 3")
    w("send X")
    w("expect-step boots 1")
    w("send X")
    w("expect wake=EXT1 pins=0x1")
    w("")
    w("# ---- what the log cannot judge (each answered here; a meter where it says so)")
    w("confirm With a meter on the cell: deep sleep (OFF) draws well under 1 mA, BOOST_EN and DISP held? (n if not measured)")
    w("confirm On battery alone (USB out): every key answers at once after a few seconds idle (light sleep's wakes)?")
    w("confirm On battery: the current between keys is far below the current while a key is held? (n if not measured)")
    w("confirm On battery: a beep sounds whole, and a running game keeps moving (no light sleep in a tone or a tick)?")
    w("confirm On battery: SYS (BLUE C) shows BATT, and it reads the same after OFF and C?")
    w("say Later, not now: leave it OFF for two hours; the image should still be sharp (the 100-minute refresh).")
    w("say Done. Send bringup.log to abacus.")
    return "\n".join(L) + "\n"


def main():
    text = session()
    if "--check" in sys.argv:
        if open(OUT, encoding="utf-8").read() != text:
            sys.exit("gen_bringup: device/reva/bringup.txt is not what the generator gives (run it)")
        return
    open(OUT, "w", encoding="utf-8").write(text)


if __name__ == "__main__":
    main()
