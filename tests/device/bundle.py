#!/usr/bin/env python3
"""Packs make test's vector files into one C source for the on-chip test (tests/device).

    python3 tests/device/bundle.py OUT.c [--small]

The list mirrors the Makefile's test target: the key-vector files, the format-vector files,
and the three fuzz files, generated here by the same commands and seeds as make test.
--small cuts the fuzz counts to a tenth, for a part whose flash cannot hold the full set (the
ESP32-C6FH4's 4 MB: the decimal library alone is 3.4 MB).
Stdlib only; run from anywhere."""
import os, subprocess, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
KEY = ["001", "003", "004", "005", "006", "007", "008", "009", "010", "011", "012", "013", "014", "015", "015b", "016", "017"]
FMT = ["007-fmt", "008-fmt", "009-fmt", "010-fmt", "002"]
FUZZ = [("eqn_fuzz", 2000), ("prog_fuzz", 1000), ("veckey_fuzz", 3000)]


def c_literal(data):
    """The bytes as C string literal lines, every line under 4095 characters."""
    out, line = [], []
    for b in data:
        if b == 0x0A:
            line.append("\\n")
            out.append('"' + "".join(line) + '"')
            line = []
            continue
        ch = chr(b)
        if ch in '"\\':
            line.append("\\" + ch)
        elif 0x20 <= b < 0x7F and ch != "?":         # ? avoids trigraphs
            line.append(ch)
        else:
            line.append('\\%03o' % b)                # octal: three digits always end it
        if len(line) > 1000:
            out.append('"' + "".join(line) + '"')
            line = []
    if line:
        out.append('"' + "".join(line) + '"')
    return "\n".join(out) if out else '""'


def main():
    out = sys.argv[1]
    small = "--small" in sys.argv[2:]
    files = []                                       # (name, is_fmt, bytes)
    for k in KEY:
        files.append((f"work/{k}-vectors.txt", 0, open(os.path.join(ROOT, f"work/{k}-vectors.txt"), "rb").read()))
    for name, count in FUZZ:
        n = count // 10 if small else count
        text = subprocess.run([sys.executable, os.path.join(ROOT, f"tests/{name}.py"), "1", str(n)],
                              check=True, capture_output=True).stdout
        files.append((f"{name} 1 {n}", 0, text))
    for k in FMT:
        files.append((f"work/{k}-vectors.txt", 1, open(os.path.join(ROOT, f"work/{k}-vectors.txt"), "rb").read()))
    # unit 016: the golden state image, for the save and load timing (kind 2)
    files.append(("tests/golden-v1.img", 2, open(os.path.join(ROOT, "tests/golden-v1.img"), "rb").read()))
    with open(out, "w") as f:
        f.write("/* Generated by tests/device/bundle.py; do not edit. */\n#include \"bundle.h\"\n\n")
        for i, (name, fmt, data) in enumerate(files):
            f.write(f"static const char T{i}[] =\n{c_literal(data)};\n\n")
        f.write("const bundle_file BUNDLE[] = {\n")
        for i, (name, fmt, data) in enumerate(files):
            f.write(f'    {{"{name}", {fmt}, T{i}, {len(data)}}},\n')
        f.write("};\nconst unsigned BUNDLE_COUNT = sizeof BUNDLE / sizeof BUNDLE[0];\n")
    total = sum(len(d) for _, _, d in files)
    print(f"bundle.py: {len(files)} files, {total} bytes -> {out}", file=sys.stderr)


if __name__ == "__main__":
    main()
