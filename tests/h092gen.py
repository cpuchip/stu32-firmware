import sys, random, math, os
sys.stdout.reconfigure(encoding='utf-8')
OUT = sys.argv[1]


def b(k, s):
    """content bytes that fill exactly k sectors of s bytes, header (32 B) counted in or not"""
    return k * s - 100


L = []
w = L.append
w("# abacus's hidden cases for unit 092 (the store's wear), written 2026-11-09 from soroban's blueprint at stu32-firmware")
w("# b59caec (work/092-store-wear.md with Revision 1: a true circular buffer) and the store_sim interface in soroban's #14139.")
w("# Sizes are chosen as k*s - 100 content bytes, so an image is k sectors whether or not its 32 B header is counted in")
w("# them. Cut-everywhere cases use 256 B sectors so CUTALL's cost stays small; the sector geometry (128 and 18) is the")
w("# partitions' own. OLD pins seq; a SAVE is expected to take the newest seq + 1. Erase bounds are lo..hi bands, since a")
w("# blank sector may or may not be erased before its first write.")
w("#")
w("# An older firmware's two-slot images load, and the higher seq wins (real geometry)")
w("PART 128 4096")
w(f"OLD 0 {b(2, 4096)} 10")
w("REBOOT")
w("EXPECT LOAD 10")
w(f"OLD 1 {b(2, 4096)} 9")
w("REBOOT")
w("EXPECT LOAD 10")
w(f"OLD 1 {b(2, 4096)} 11")
w("REBOOT")
w("EXPECT LOAD 11")
w("# a ring save after old slots: it takes seq 12 and loads")
w(f"SAVE {b(2, 4096)}")
w("REBOOT")
w("EXPECT LOAD 12")
w("#")
w("# A cut early in a save leaves the newest finished image")
w("PART 128 4096")
w(f"OLD 0 {b(1, 4096)} 20")
w(f"CUT {b(2, 4096)} 3")
w("EXPECT LOAD 20")
w("#")
w("# The counterexample of #14138 (state geometry): newest at 61-76, then a 64-sector save, cut at every operation")
w("PART 128 256")
w(f"OLD 0 {b(61, 256)} 100")
w(f"SAVE {b(16, 256)}")
w("REBOOT")
w("EXPECT LOAD 101")
w(f"CUTALL {b(64, 256)}")
w("REBOOT")
w("EXPECT LOAD 102")
w("# and the next save after the wrapped one, cut at every operation too")
w(f"CUTALL {b(64, 256)}")
w("REBOOT")
w("EXPECT LOAD 103")
w("#")
w("# The same for the apps' geometry: newest at 8-15, then a 9-sector save")
w("PART 18 256")
w(f"OLD 0 {b(8, 256)} 100")
w(f"SAVE {b(8, 256)}")
w("REBOOT")
w("EXPECT LOAD 101")
w(f"CUTALL {b(9, 256)}")
w("REBOOT")
w("EXPECT LOAD 102")
w("#")
# Wear spread, real geometry: 1,280 one-sector saves go round the 128-sector ring ten times.
w("# Wear: 1,280 one-sector saves (a typical state) go round the ring ten times")
w("PART 128 4096")
w(f"OLD 0 {b(1, 4096)} 1000")
for _ in range(1280):
    w(f"SAVE {b(1, 4096)}")
w("REBOOT")
w("EXPECT LOAD 2280")
w("EXPECT MAXERASES 11")
w("EXPECT ERASES 0 9 11")
w("EXPECT ERASES 64 9 11")
w("EXPECT ERASES 127 9 11")
w("#")
# Random sizes to the cap over many wraps (256 B sectors), then cut everywhere in one last save.
R = random.Random(92)
sizes = [R.randint(1, 64) for _ in range(400)]
total = sum(sizes)
hi = math.ceil(total / 128) + 2
w(f"# Random sizes 1-64 sectors (seed 92), 400 saves, {total} sectors written: about {total / 128:.1f} times round the ring")
w("PART 128 256")
w(f"OLD 0 {b(1, 256)} 5000")
for k in sizes:
    w(f"SAVE {b(k, 256)}")
w("REBOOT")
w("EXPECT LOAD 5400")
w(f"EXPECT MAXERASES {hi}")
w(f"CUTALL {b(64, 256)}")
w("REBOOT")
w("EXPECT LOAD 5401")
open(OUT, 'w', encoding='utf-8', newline='\n').write('\n'.join(L) + '\n')
